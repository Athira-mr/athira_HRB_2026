
# =========================================================
# CUSTOM API EXCEPTION HANDLER
# =========================================================

# Imports DRF's default exception handler.
from rest_framework.views import exception_handler


def custom_exception_handler(exc, context):
    """
    Converts handled DRF exceptions into a consistent JSON format.

    For example, validation errors, authentication errors
    and not-found errors will follow the same response structure.
    """

    # Let Django REST Framework determine the correct status code
    # and response data for the original exception.
    response = exception_handler(exc, context)

    # If DRF cannot handle the exception, return None.
    # Django will then handle it as an unexpected server error.
    if response is None:
        return None

    # Get the original error details generated by DRF.
    error_details = response.data

    # Extract a readable message when DRF provides a detail field.
    if isinstance(error_details, dict):
        message = error_details.get(
            "detail",
            "The request could not be processed."
        )
    else:
        message = "The request could not be processed."

    # Replace the original response with a consistent structure.
    response.data = {
        "success": False,
        "status_code": response.status_code,
        "message": str(message),
        "errors": error_details,
    }

    return response
